import { Link, useLocation } from 'react-router-dom';
import { useAppStore } from '../../store';
import usePageMeta from '../../hooks/usePageMeta';
import { openCookieSettings } from '../../store/cookies';

/** The date of this edition; bump with LEGAL_VERSION in app/routes/privacy.py. */
export const LEGAL_DATE = '28 октября 2026 г.';

type Doc = 'privacy' | 'consent' | 'terms';

const TITLES: Record<Doc, string> = {
  privacy: 'Политика обработки персональных данных',
  consent: 'Согласие на обработку персональных данных',
  terms: 'Условия продажи и использования сайта',
};

/** The operator's details from the admin panel (Контакты, FAQ, Метрика → Реквизиты). */
function useOperator() {
  const s = useAppStore((st) => st.settings);
  const v = (k: string) => s[k]?.trim() || 'не указано';
  return {
    name: v('legal_name'),
    inn: v('legal_inn'),
    ogrn: v('legal_ogrn'),
    address: v('legal_address'),
    email: s.legal_email?.trim() || s.contact_email_2?.trim() || s.contact_email_1?.trim() || 'не указано',
    hosting: s.legal_hosting?.trim() || '',
  };
}

/**
 * The legal pages: the personal data policy, the consent to processing (a
 * document of its own, as 152-ФЗ asks since 1 September 2025) and the terms
 * of sale. Texts are a careful template — the operator's details come from
 * the admin panel, and a lawyer should read them before launch.
 */
export default function LegalPage() {
  const { pathname } = useLocation();
  const doc: Doc = pathname.startsWith('/consent') ? 'consent' : pathname.startsWith('/terms') ? 'terms' : 'privacy';
  const op = useOperator();
  usePageMeta(`${TITLES[doc]} — RefSale`, `${TITLES[doc]} сайта refsale.ru`, `/${doc}`);

  return (
    <main className="pt-[calc(var(--header-h,104px)+28px)] pb-24 max-md:pb-16">
      <div className="max-w-[880px] mx-auto px-6 max-sm:px-4">
        <nav className="flex flex-wrap gap-2 mb-6" aria-label="Документы">
          {(Object.keys(TITLES) as Doc[]).map((d) => (
            <Link
              key={d}
              to={`/${d}`}
              className={`h-9 px-3.5 rounded-ctl-sm border-2 text-[12.5px] font-bold inline-flex items-center ${d === doc ? 'bg-ink border-ink text-sun' : 'bg-card border-ink/15 text-ink hover:border-ink'}`}
            >
              {d === 'privacy' ? 'Политика' : d === 'consent' ? 'Согласие' : 'Условия продажи'}
            </Link>
          ))}
        </nav>
        <article className="bg-card border-2 border-ink rounded-[24px] max-sm:rounded-[20px] shadow-[0_6px_0_#111] p-10 max-md:p-7 max-sm:p-5 legal">
          <h1 className="font-display text-[clamp(26px,3.4vw,40px)] leading-[1.1] text-ink">{TITLES[doc]}</h1>
          <p className="mt-3 text-[13px] text-muted">Редакция от {LEGAL_DATE}</p>
          {doc === 'privacy' && <Privacy op={op} />}
          {doc === 'consent' && <Consent op={op} />}
          {doc === 'terms' && <Terms op={op} />}
        </article>
      </div>
    </main>
  );
}

